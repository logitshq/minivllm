def read(path):return json.loads(path.read_bytes())
def sha(path):
    assert Path(path).suffix not in ('.safetensors','.gguf'),'no tensor/model payload reads'
    h=hashlib.sha256()
    with Path(path).open('rb') as stream:
        while raw:=stream.read(1<<20):h.update(raw)
    return h.hexdigest()
def save(name,value):
    with (D/name).open('x') as stream:json.dump(value,stream,indent=2);stream.write('\n')
