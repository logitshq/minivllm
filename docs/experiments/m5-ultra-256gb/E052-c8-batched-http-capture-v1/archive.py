"""Archive E052 v1 failed readiness and restored service; preserve original FAIL."""
import argparse
import hashlib
import json
import tarfile
from pathlib import Path
R=Path('/Users/ryanli/code/minivllm');A=R/'.artifacts/m5-ultra-256gb';B=R/'bench/m5_ultra_256gb';D=Path(__file__).resolve().parent
LABEL='c8-batched-mb50-two-waves'
PLAN_SHA='3e14ce911125eb46147943d5024510414271198984588dd91fea8319df8947e6'
SPEC_SHA='8f7d0095c98d70bb4d72609a1a91e48581da32fc0695e6363f0fadbafa0c281c'
def read(path):return json.loads(path.read_bytes())
def sha(path):
    assert Path(path).suffix not in ('.safetensors','.gguf'),'no tensor/model payload reads'
    h=hashlib.sha256()
    with Path(path).open('rb') as stream:
        while raw:=stream.read(1<<20):h.update(raw)
    return h.hexdigest()
def save(name,value):
    with (D/name).open('x') as stream:json.dump(value,stream,indent=2);stream.write('\n')
def archive():
    execution=A/'c8-batched-http-v1-execution';plan=read(execution/'plan.json');resource=read(D/'failure-resource-review.json')
    assert sha(execution/'plan.json')==PLAN_SHA and resource['status']=='PASS_SAVED_FAILURE_RESTORE' and resource['errors']==[]
    child=A/'c8-batched-http-v1-screen/trials'/LABEL;complete=read(child/'complete.json')
    assert complete['status']=='FAIL' and complete['schema']=='c8-batched-http-result-v1'
    assert complete['errors']==[dict(phase='readiness',type='ValueError',message='actual startup identity differs from capture contract')]
    assert sha(child/'spec.json')==SPEC_SHA and resource['generation_requests']==0
    assert not (child/'group.json').exists() and not (child/'joined-input').exists()
    assert not list(child.rglob('*.safetensors'))
    roots={name:A/name for name in ['c8-batched-http-v1-'+x for x in ('execution','screen','lease')]}
    roots['source/c8_batched_http_v1']=B/'c8_batched_http_v1'
    for pattern in ('c8-batched-http-cpu-*','c8-batched-http-owner-cpu-*'):
        for folder in A.glob(pattern):
            if folder.is_dir():roots[folder.name]=folder
    members=[];missing=[];excluded=[]
    def add(path,arcname):
        assert not path.is_symlink(),str(path)
        if path.suffix in ('.safetensors','.gguf','.pyc') or '__pycache__' in path.parts:
            excluded.append(dict(path=str(path),bytes=path.stat().st_size,reason='Model tensor or generated bytecode.'));return
        members.append(dict(path=str(arcname),source=str(path),bytes=path.stat().st_size,sha256=sha(path)))
    for name,folder in roots.items():
        if not folder.is_dir():missing.append(str(folder));continue
        for path in sorted(folder.rglob('*')):
            if path.is_file():add(path,Path(name)/path.relative_to(folder))
    for i,(path,digest) in enumerate(sorted(plan['pins'].items())):
        p=Path(path);assert p.stat().st_size<64*(1<<20) and sha(p)==digest
        if not any(m['source']==path for m in members):add(p,Path('source-pins')/f'{i:03d}-{p.name}')
    for name in ('failure_resource_audit.py','failure-resource-review.json','resource-command.json','resource-execution.json','resource-stdout.txt','resource-stderr.txt','execution-provenance.json',Path(__file__).name):
        add(D/name,Path('independent-review')/name)
    add(B/'concurrency_config_analysis_v1/resources.py','independent-review/frozen-resource-readers.py')
    assert len({m['path'] for m in members})==len(members)
    save('manifest.json',dict(members=members,missing_requested_directories=missing,excluded=excluded))
    save('references.json',dict(source_pins=plan['pins'],plan=dict(path=str(execution/'plan.json'),sha256=PLAN_SHA),
        resource_audit=dict(path=str(D/'failure-resource-review.json'),sha256=sha(D/'failure-resource-review.json')),
        raw_join_performed=False,identity_difference=resource['identity_difference'],
        scope='Original FAIL remains; only saved readiness/resource/restore facts. Model/runtime payloads not rehashed by this archiver.'))
    with tarfile.open(D/'evidence.tar.gz','w:gz',compresslevel=6) as tar:
        for m in members:
            p=Path(m['source']);assert p.stat().st_size==m['bytes'] and sha(p)==m['sha256'];tar.add(p,arcname=m['path'],recursive=False)
    expected={m['path']:m for m in members};seen=set()
    with tarfile.open(D/'evidence.tar.gz','r|gz') as tar:
        for entry in tar:
            assert entry.isfile() and entry.name in expected and entry.name not in seen
            m=expected[entry.name];h=hashlib.sha256();size=0
            with tar.extractfile(entry) as stream:
                while raw:=stream.read(1<<20):size+=len(raw);h.update(raw)
            assert entry.size==size==m['bytes'] and h.hexdigest()==m['sha256']==sha(Path(m['source']));seen.add(entry.name)
    assert seen==set(expected)
    save('summary.json',dict(status='ARCHIVED_FAILED_READINESS',original_final=read(execution/'final.json'),
        original_screen=read(A/'c8-batched-http-v1-screen/result.json'),original_trial=complete,
        generation_requests=0,readiness_polls=resource['readiness_polls'],raw_join_performed=False,
        resources={k:v for k,v in resource.items() if k not in ('inputs','baseline')},original_pending_fields_preserved=True,
        numerical_qualified=False,full_state_qualified=False,candidate_http_history_qualified=False,
        performance_qualified=False,engine_pareto_point=False,
        scope='Actual v1 readiness identity mismatch; no generation requests. Source-only capture drafts retained but not executed as success audits.'))
    verification=dict(status='PASS_ARCHIVE_INTEGRITY',members=len(members),uncompressed_bytes=sum(m['bytes'] for m in members),
        archive_bytes=(D/'evidence.tar.gz').stat().st_size,evidence_sha256=sha(D/'evidence.tar.gz'),manifest_sha256=sha(D/'manifest.json'),
        all_members_reread_size_sha_and_source_match=True,missing_requested_directories=missing,excluded_count=len(excluded),model_weights_archived=False)
    save('archive-verification.json',verification);print(json.dumps(verification))
if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--run',action='store_true');args=p.parse_args()
    if not args.run:print('Inert: explicit --run archives only the closed E052 v1 readiness failure.')
    else:archive()
