"""E054 small evidence archive; retain audited local snapshots by reference only."""
import argparse
import hashlib
import json
import tarfile
from pathlib import Path

R=Path('/Users/ryanli/code/minivllm');A=R/'.artifacts/m5-ultra-256gb';B=R/'bench/m5_ultra_256gb';D=Path(__file__).resolve().parent

def read(p):return json.loads(Path(p).read_bytes())
def sha(p):
    p=Path(p);assert p.suffix not in ('.safetensors','.gguf'),'no tensor/model payload reads'
    h=hashlib.sha256()
    with p.open('rb') as f:
        while data:=f.read(1<<20):h.update(data)
    return h.hexdigest()
def save(name,value):
    with (D/name).open('x') as f:json.dump(value,f,indent=2,allow_nan=False);f.write('\n')

def archive(audit_path,audit_source):
    n=A/'c1-verifier-cost-v1-numerical';x=A/'c1-verifier-cost-v1-execution'
    plan=read(x/'plan.json');complete=read(n/'complete.json');audit=read(audit_path);resource=read(D/'resource-review.json')
    assert complete['schema']=='C1-verifier-cost-result-v1' and complete['status']=='PASS_LOCAL_COST_ONLY'
    assert complete['numerical_screen_qualified'] is complete['device_cleanup_completed'] is complete['source_model_pins_rechecked'] is True
    assert audit['status']=='PASS' and audit['local_cost_audited'] is True
    assert audit['raw_files']==32 and audit['tensor_pairs']==2064 and audit['timing_count']==400 and audit['group_count']==20
    assert audit['audit_source_sha256']==sha(audit_source) and audit['complete_sha256']==sha(n/'complete.json')
    assert resource['status']=='PASS_SAVED_OBSERVATIONS' and resource['errors']==[]
    assert all(complete[k] is audit[k] is False for k in ('http_qualified','performance_qualified','engine_pareto_point'))
    pairs={p['label']:p for p in audit['pairs']};raw=[]
    for row in complete['raw_comparisons']:
        assert pairs[row['label']]['bit_equal'] is True
        for arm,desc in zip(('reference','actual'),row['files']):
            p=n/desc['path'];side=p.with_suffix('.json');st=p.stat()
            assert desc==read(side) and desc['path']==row['label']+'/'+arm+'.safetensors'
            assert not p.is_symlink() and desc['sha256']==pairs[row['label']][arm+'_sha256'] and desc['finite'] is True
            raw.append(dict(path=str(p),relative_path=desc['path'],bytes=st.st_size,sha256=desc['sha256'],mtime_ns=st.st_mtime_ns,
                sidecar=str(side),sidecar_sha256=sha(side),payload_sha_evidence='Validated by completed independent raw-byte audit; metadata archiver does not reread payload.'))
    assert len(raw)==32 and {p['path'] for p in raw}=={str(p) for p in n.rglob('*.safetensors')}
    save('raw-file-references.json',dict(raw_files=raw,total_bytes=sum(r['bytes'] for r in raw),raw_payload_archived=False,
        raw_payload_rehashed_by_archiver=False,independent_audit=dict(path=str(audit_path),sha256=sha(audit_path)),
        scope='Original local paths and current sizes; original-byte SHA values are from sidecars independently validated by the passing saved-byte audit.'))
    roots={name:A/name for name in ['c1-verifier-cost-v1-'+s for s in ('execution','owner','lease','numerical')]}
    patterns=('c1-verifier-cost-*-cpu-*','rowwise-native-verify-cost-cpu-*','c1-verifier-cost-v1-independent-execution-*')
    for pattern in patterns:
        for p in sorted(A.glob(pattern)):
            if p.is_dir():roots[p.name]=p
    roots['source/rowwise_native_verify_cost_v1']=B/'rowwise_native_verify_cost_v1'
    roots['source/'+audit_source.parent.name]=audit_source.parent
    if (D/'chart').is_dir():roots['chart']=D/'chart'
    members=[];excluded=[];missing=[]
    def add(p,name):
        p=Path(p);assert not p.is_symlink()
        if p.suffix in ('.safetensors','.gguf','.pyc') or '__pycache__' in p.parts:
            excluded.append(dict(path=str(p),bytes=p.stat().st_size,reason='Local tensor payload or generated bytecode.'));return
        members.append(dict(path=str(name),source=str(p),bytes=p.stat().st_size,sha256=sha(p)))
    for label,folder in roots.items():
        if not folder.is_dir():missing.append(str(folder));continue
        for p in sorted(folder.rglob('*')):
            if p.is_file():add(p,Path(label)/p.relative_to(folder))
    for p in sorted(A.glob('c1-verifier-cost-v1-independent*.json')):
        if p.is_file():add(p,Path('independent-audit-attempts')/p.name)
    if str(audit_path) not in {m['source'] for m in members}:add(audit_path,'independent-audit-final.json')
    for name in ('archive.py','resource_audit.py','resource-review.json','resource-review-command.json','resource-review-execution.json',
                 'resource-review-stdout.txt','resource-review-stderr.txt','execution-provenance.json','raw-file-references.json'):
        add(D/name,Path('independent-review')/name)
    add(B/'concurrency_config_analysis_v1/resources.py','independent-review/frozen-resource-readers.py')
    assert len({m['path'] for m in members})==len(members)
    save('references.json',dict(source_pins=plan['pins'],runtime_pins=plan['runtime_pins'],
        independent_audit=dict(path=str(audit_path),sha256=sha(audit_path),source=str(audit_source),source_sha256=sha(audit_source)),
        resource_review_sha256=sha(D/'resource-review.json'),scope='No model/runtime/tensor payload was rehashed or copied by the metadata archiver.'))
    save('manifest.json',dict(members=members,excluded=excluded,missing_requested_directories=missing))
    with tarfile.open(D/'evidence.tar.gz','w:gz',compresslevel=6) as tar:
        for m in members:
            p=Path(m['source']);assert p.stat().st_size==m['bytes'] and sha(p)==m['sha256'];tar.add(p,arcname=m['path'],recursive=False)
    expected={m['path']:m for m in members};seen=set()
    with tarfile.open(D/'evidence.tar.gz','r|gz') as tar:
        for entry in tar:
            assert entry.isfile() and entry.name in expected and entry.name not in seen
            m=expected[entry.name];h=hashlib.sha256();size=0
            with tar.extractfile(entry) as f:
                while data:=f.read(1<<20):size+=len(data);h.update(data)
            assert entry.size==size==m['bytes'] and h.hexdigest()==m['sha256']==sha(m['source']);seen.add(entry.name)
    assert seen==set(expected)
    save('summary.json',dict(status='ARCHIVED_LOCAL_COST_ONLY',original_child_status=complete['status'],
        independent_audit=audit,resource_review={k:v for k,v in resource.items() if k!='inputs'},original_final=read(x/'final.json'),
        raw_files_local=len(raw),raw_bytes_local=sum(r['bytes'] for r in raw),raw_payload_archived=False,
        raw_payload_rehashed_by_archiver=False,original_failure_attempts_preserved=True,
        full_model_qualified=False,http_qualified=False,performance_qualified=False,engine_pareto_point=False,
        scope='Six selected-prefix/continuation numerical cases; complete verifier local cost against native AR(T), k=T timings only. No draft/acceptance/scheduler/HTTP cost or engine speedup claim.'))
    verification=dict(status='PASS_METADATA_ARCHIVE_INTEGRITY',members=len(members),uncompressed_bytes=sum(m['bytes'] for m in members),
        archive_bytes=(D/'evidence.tar.gz').stat().st_size,evidence_sha256=sha(D/'evidence.tar.gz'),manifest_sha256=sha(D/'manifest.json'),
        all_members_reread_size_sha_and_source_match=True,missing_requested_directories=missing,excluded_count=len(excluded),raw_payload_archived=False)
    save('archive-verification.json',verification);print(json.dumps(verification))

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--audit',type=Path,required=True);p.add_argument('--audit-source',type=Path,required=True);a=p.parse_args()
    archive(a.audit.resolve(),a.audit_source.resolve())
