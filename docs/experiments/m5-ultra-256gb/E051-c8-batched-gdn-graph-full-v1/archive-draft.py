import tarfile
from pathlib import Path

R=Path('/Users/ryanli/code/minivllm');A=R/'.artifacts/m5-ultra-256gb';B=R/'bench/m5_ultra_256gb';D=Path(__file__).resolve().parent

def read(path):return json.loads(path.read_bytes())
def sha(path):
    assert path.suffix not in ('.safetensors','.gguf'),'no model/tensor payload reads'
    h=hashlib.sha256()
    with path.open('rb') as f:
        while data:=f.read(1<<20):h.update(data)
    return h.hexdigest()
def save(name,value):
    with (D/name).open('x') as f:json.dump(value,f,indent=2);f.write('\n')

def archive(audit_path,audit_execution,audit_source):
    x=A/'c8-batched-full-v1-execution';n=A/'c8-batched-full-v1-numerical'
    plan=read(x/'plan.json');complete=read(n/'complete.json');resource=read(D/'resource-review.json');audit=read(audit_path)
    assert complete['schema']=='c8-batched-gdn-graph-prefix-result-v1' and complete['status']=='DIAGNOSTIC_PREFIX_COMPLETE'
    assert complete['completion_state']=='INCOMPLETE_BY_DESIGN' and complete['full_history_qualified'] is complete['performance_qualified'] is False
    assert complete['prefix']['steps']==49 and complete['prefix']['completed']==[]
    assert resource['status']=='PASS_SAVED_OBSERVATIONS' and resource['errors']==[]
    assert audit['status']=='PASS' and audit['prefix_receipts_verified'] is True
    assert audit['completion_state']=='INCOMPLETE_BY_DESIGN' and audit['offline_tensor_bytes_rechecked'] is False
    assert audit['audit_source_sha256']==sha(audit_source) and audit['terminal_sha256'][str(n/'complete.json')]==sha(n/'complete.json')
    assert audit['inherited_prefix_audit']['ledger']['sha256']==sha(n/'inherited/base/steps.jsonl')
    assert not list(n.rglob('*.safetensors'))
    roots={name:A/name for name in ['c8-batched-full-v1-'+suffix for suffix in ('execution','owner','lease','numerical')]
           +['c8-batched-full-cpu-v1','c8-batched-full-cpu-v2','c8-batched-full-owner-cpu-v1']}
    roots['source/c8_batched_full_v1']=B/'c8_batched_full_v1';roots['independent-ledger-execution']=audit_execution
    roots['source/c8_batched_full_analysis_v1']=B/'c8_batched_full_analysis_v1'
    roots['independent-ledger-attempt1']=A/'c8-batched-full-v1-independent-audit-attempt1'
    roots['independent-ledger-cpu-v1']=A/'c8-batched-full-audit-cpu-v1'
    members=[];missing=[];excluded=[]
    def add(path,arcname):
        assert not path.is_symlink(),str(path)
        if path.suffix in ('.safetensors','.gguf','.pyc') or '__pycache__' in path.parts:
            excluded.append(dict(path=str(path),bytes=path.stat().st_size,reason='Tensor payload or generated bytecode.'));return
        members.append(dict(path=str(arcname),source=str(path),bytes=path.stat().st_size,sha256=sha(path)))
    for name,folder in roots.items():
        if not folder.is_dir():missing.append(str(folder));continue
        for path in sorted(folder.rglob('*')):
            if path.is_file():add(path,Path(name)/path.relative_to(folder))
    add(audit_path,'independent-ledger-audit.json');add(audit_source,'independent-review/ledger-auditor.py')
    inherited=Path(audit['inherited_auditor']['path']);assert sha(inherited)==audit['inherited_auditor']['sha256']
    add(inherited,'independent-review/inherited-ledger-auditor.py')
    for i,(path,digest) in enumerate(sorted(audit['inherited_prefix_audit']['helper_sources'].items())):
        assert sha(Path(path))==digest;add(Path(path),f'independent-review/helper-{i}-{Path(path).name}')
    for name in ('resource_audit.py','resource-review.json','resource-command.json','resource-execution.json','resource-stdout.txt','resource-stderr.txt','execution-provenance.json','archive.py'):
        add(D/name,Path('independent-review')/name)
    add(B/'concurrency_config_analysis_v1/resources.py','independent-review/frozen-resource-readers.py')
    assert len({m['path'] for m in members})==len(members)
    save('references.json',dict(source_pins=plan['pins'],runtime_pins=plan['runtime_pins'],
        numerical_scope='Full tensor payloads were not retained; offline ledger audit is not an independent raw-tensor recomputation.',
        runtime_scope='Original verification receipts retained; archiver did not read model/runtime payloads.',
        independent_ledger_audit=dict(path=str(audit_path),sha256=sha(audit_path)),resource_review_sha256=sha(D/'resource-review.json')))
    save('manifest.json',dict(members=members,missing_requested_directories=missing,excluded=excluded))
    with tarfile.open(D/'evidence.tar.gz','w:gz',compresslevel=6) as tar:
        for m in members:
            p=Path(m['source']);assert p.stat().st_size==m['bytes'] and sha(p)==m['sha256'];tar.add(p,arcname=m['path'],recursive=False)
    expected={m['path']:m for m in members};seen=set()
    with tarfile.open(D/'evidence.tar.gz','r|gz') as tar:
        for entry in tar:
            assert entry.isfile() and entry.name in expected and entry.name not in seen
            m=expected[entry.name];h=hashlib.sha256();size=0
            with tar.extractfile(entry) as f:
                while data:=f.read(1<<20):size+=len(data);h.update(data)
            assert entry.size==size==m['bytes'] and h.hexdigest()==m['sha256']==sha(Path(m['source']));seen.add(entry.name)
    assert seen==set(expected)
    save('summary.json',dict(status='ARCHIVED_PREFIX_DIAGNOSTIC',original_child_status=complete['status'],
        original_completion_state=complete['completion_state'],prefix_steps=complete['prefix']['steps'],
        completed_requests=complete['prefix']['completed'],active_requests=len(complete['prefix']['active_request_ids']),
        future_unadmitted_requests=len(complete['prefix']['future_unadmitted_request_ids']),
        independent_ledger_audit=audit,resource_review={k:v for k,v in resource.items() if k!='inputs'},
        original_final=read(x/'final.json'),reported_peak_mlx_bytes=complete['peak_mlx_bytes'],
        original_cpu_v1=read(A/'c8-batched-full-cpu-v1/result.json'),original_cpu_v2=read(A/'c8-batched-full-cpu-v2/result.json'),
        original_pending_fields_preserved=True,full_history_qualified=False,performance_qualified=False,engine_pareto_point=False,
        scope='Warm49 diagnostic only; screen565 and full original 1030-step history are not replayed. No raw full tensor files were retained.'))
    verification=dict(status='PASS_METADATA_ARCHIVE_INTEGRITY',members=len(members),uncompressed_bytes=sum(m['bytes'] for m in members),
        archive_bytes=(D/'evidence.tar.gz').stat().st_size,evidence_sha256=sha(D/'evidence.tar.gz'),manifest_sha256=sha(D/'manifest.json'),
        all_members_reread_size_sha_and_source_match=True,missing_requested_directories=missing,excluded_count=len(excluded))
    save('archive-verification.json',verification);print(json.dumps(verification))

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--audit',type=Path,required=True)
