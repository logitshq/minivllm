def read(path):return json.loads(path.read_bytes())
def sha(path):
    assert path.suffix not in ('.safetensors','.gguf'),'no model/tensor payload reads'
    h=hashlib.sha256()
    with path.open('rb') as f:
        while data:=f.read(1<<20):h.update(data)
    return h.hexdigest()
def save(name,value):
    with (D/name).open('x') as f:json.dump(value,f,indent=2);f.write('\n')

def archive(audit_path,audit_execution,audit_source):
    x=A/'c8-batched-http-replay-v1-execution';n=A/'c8-batched-http-replay-v1-numerical'
    plan=read(x/'plan.json');complete=read(n/'complete.json');resource=read(D/'resource-review.json');audit=read(audit_path)
