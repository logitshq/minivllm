    assert audit['recorded_history_verified'] is audit['qualified'] is audit['http_history_qualified'] is audit['candidate_http_capture_qualified'] is True
    assert audit['offline_tensor_bytes_rechecked'] is audit['performance_qualified'] is audit['owner_resources_restore_qualified'] is False
    assert audit['audit_source_sha256']==sha(audit_source) and audit['terminal_sha256'][str(n/'complete.json')]==sha(n/'complete.json')
    assert audit['ledger']['sha256']==sha(n/'base/steps.jsonl')
    assert not list(n.rglob('*.safetensors'))
    roots={name:A/name for name in ['c8-batched-http-replay-v1-'+suffix for suffix in ('execution','owner','lease','numerical')]
           +['c8-batched-http-replay-cpu-v1','c8-batched-http-replay-owner-cpu-v1']}
    roots['source/c8_batched_http_replay_v1']=B/'c8_batched_http_replay_v1';roots['independent-ledger-execution']=audit_execution
    roots['source/c8_batched_http_replay_analysis_v1']=B/'c8_batched_http_replay_analysis_v1'
