"""Retain all explicitly listed E045 attempts; gzip then reread every member.

No benchmark execution. Model tensor payloads and bytecode are excluded with an
explicit inventory; ordinary JSON/raw-SSE/log/source evidence is retained.
"""
import hashlib
import json
import shutil
import tarfile
from pathlib import Path

R=Path('/Users/ryanli/code/minivllm'); A=R/'.artifacts/m5-ultra-256gb'; D=Path(__file__).resolve().parent
NAMES=(['concurrency-config-v1-'+x for x in ('screen','execution','lease')]
       +['concurrency-config-v2-'+x for x in ('screen','execution','lease','independent-audit','resource-audit','chart','chart-layout2')]
       +['concurrency-config-cpu-'+x for x in ('v1','v2','v3')]
       +['concurrency-config-audit-cpu-v1','concurrency-config-owner-cpu-v1'])

def sha(path):
    h=hashlib.sha256()
    with path.open('rb') as f:
        while chunk:=f.read(1<<20):h.update(chunk)
    return h.hexdigest()

def save(name,value):
    with (D/name).open('x') as f:json.dump(value,f,indent=2);f.write('\n')

members=[];missing=[];excluded=[]
roots={name:A/name for name in NAMES}
roots.update({'sources/'+name:R/'bench/m5_ultra_256gb'/name for name in
              ('concurrency_config_v1','concurrency_config_v2','concurrency_config_analysis_v1')})
for label,folder in roots.items():
    if not folder.is_dir():missing.append(dict(path=str(folder),reason='Requested directory not present'));continue
    for path in sorted(folder.rglob('*')):
        if not path.is_file():continue
        assert not path.is_symlink(),str(path)
        if path.suffix in ('.safetensors','.gguf','.pyc') or '__pycache__' in path.parts:
            excluded.append(dict(path=str(path),bytes=path.stat().st_size,reason='Model payload or generated bytecode; not experimental raw evidence.'));continue
        members.append(dict(path=str(Path(label)/path.relative_to(folder)),source=str(path),bytes=path.stat().st_size,sha256=sha(path)))
# Preserve this independent recheck and the independently recorded visual review.
for name in ('comparison_recheck.py','comparison-recheck.json','comparison-command.json','comparison-execution.json',
             'comparison-stdout.txt','comparison-stderr.txt','visual-review.json'):
    p=D/name;members.append(dict(path='independent-review/'+name,source=str(p),bytes=p.stat().st_size,sha256=sha(p)))
assert len({m['path'] for m in members})==len(members)
save('manifest.json',dict(members=members,missing_requested_directories=missing,excluded=excluded,
    scope='Original failures retained verbatim. Integrity does not promote runtime/numeric/visual outcomes.'))
with tarfile.open(D/'evidence.tar.gz','w:gz',compresslevel=6) as tar:
    for m in members:
        p=Path(m['source']);assert p.stat().st_size==m['bytes'] and sha(p)==m['sha256']
        tar.add(p,arcname=m['path'],recursive=False)
expected={m['path']:m for m in members};seen=set()
with tarfile.open(D/'evidence.tar.gz','r|gz') as tar:
    for entry in tar:
        assert entry.name in expected and entry.name not in seen and entry.isfile()
        m=expected[entry.name];assert entry.size==m['bytes'];h=hashlib.sha256();size=0
        with tar.extractfile(entry) as f:
            while chunk:=f.read(1<<20):h.update(chunk);size+=len(chunk)
        assert size==m['bytes'] and h.hexdigest()==m['sha256']==sha(Path(m['source']))
        seen.add(entry.name)
assert seen==set(expected)
for name in ('concurrency-config-screen.png','concurrency-config-screen.svg','chartdata.json','render-receipt.json'):
    source=A/'concurrency-config-v2-chart-layout2'/name;destination=D/name
    assert not destination.exists();shutil.copyfile(source,destination);assert sha(source)==sha(destination)
references={}
for version in ('v1','v2'):
    p=A/f'concurrency-config-{version}-execution/plan.json';row=json.loads(p.read_bytes())
    references[version]=dict(plan=dict(path=str(p),sha256=sha(p)),pins=row['pins'])
save('references.json',references)
value=dict(status='PASS_ARCHIVE_INTEGRITY',members=len(members),uncompressed_bytes=sum(m['bytes'] for m in members),
    archive_bytes=(D/'evidence.tar.gz').stat().st_size,evidence_sha256=sha(D/'evidence.tar.gz'),
    manifest_sha256=sha(D/'manifest.json'),all_members_reread_size_sha_and_source_match=True,
    missing_requested_directories=missing,excluded_count=len(excluded),
    original_v1_parent_status='FAIL',original_v2_token_audit_status='FAIL_TOKEN_EQUIVALENCE',
    latest_chart_visual_review='PASS',performance_qualified=False)
save('archive-verification.json',value);print(json.dumps(value))
